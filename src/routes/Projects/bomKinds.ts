/** For a select: grouped in list order, "Fasteners · Screw". */
export const BOM_KIND_OPTIONS = BOM_GROUPS.flatMap((group) =>
  entries
    .filter(([, kind]) => kind.group === group)
    .map(([value, kind]) => ({ value, label: group === 'Other' ? kind.label : `${group} · ${kind.label}` })),
);

/** Where a kind sorts: by group, then as listed above. */
export const bomKindRank = (kind: BomPartKind) =>
  BOM_GROUPS.indexOf(BOM_KINDS[kind].group) * 1000 + entries.findIndex(([value]) => value === kind);

